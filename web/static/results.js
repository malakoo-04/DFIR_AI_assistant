/* ============================================================
   results.js — DFIR-AI frontend
   "Investigation results" page: populated by prepareResults(),
   called from progress.js once a run completes.
   ============================================================ */

function initResults() {
  document.querySelectorAll('[data-download]').forEach(function (btn) {
    btn.addEventListener('click', function () {
      mockDownload(btn.dataset.download);
    });
  });
}

function prepareResults(pipeline) {
  $('resTitle').textContent = state.invName;
  $('resSubtitle').textContent =
    pipeline.label + ' · case artifacts generated by the analysis pipeline.';
  $('resSummaryTitle').textContent = pipeline.resultTitle + ' ready';

  const secs = Math.floor((Date.now() - state.startTime) / 1000) || Math.round(pipeline.duration / 1000);
  const m = String(Math.floor(secs / 60)).padStart(2, '0');
  const s = String(secs % 60).padStart(2, '0');
  const analyst = ($('invAnalyst').value.trim()) || 'a.moreau';
  $('resSummaryMeta').textContent = 'Completed in ' + m + ':' + s + ' · ' + analyst;

  const byRun = {
    dfir: { dfir: true,  ioc: true,  haya: false, timeline: true,  mitre: true  },
    ioc:  { dfir: false, ioc: true,  haya: false, timeline: false, mitre: false },
    haya: { dfir: false, ioc: false, haya: true,  timeline: false, mitre: false },
  };
  const generated = byRun[state.runType] || byRun.dfir;

  setCardState('cardDfir', 'tagDfir', generated.dfir, 'Generated');
  setCardState('cardIoc', 'tagIoc', generated.ioc, 'Generated');
  setCardState('cardHaya', 'tagHaya', generated.haya, 'Generated');
  setCardState('cardTimeline', 'tagTimeline', generated.timeline, 'Generated');

  const mitreTag = $('tagMitre');
  const mitreCard = $('cardMitre');
  if (generated.mitre) {
    mitreTag.textContent = 'Included in DFIR report';
    mitreTag.classList.remove('not-run');
    mitreCard.classList.remove('disabled');
  } else {
    mitreTag.textContent = 'Requires DFIR report';
    mitreTag.classList.add('not-run');
    mitreCard.classList.add('disabled');
  }

  $('metaIocCount').textContent = pipeline.stats.iocs || '—';
  $('metaHayaCount').textContent =
    state.runType === 'haya' ? pipeline.stats.incidents : (generated.haya ? pipeline.stats.incidents : 58);
}

function setCardState(cardId, tagId, isGenerated, generatedLabel) {
  const card = $(cardId);
  const tag = $(tagId);
  if (!card || !tag) return;

  if (isGenerated) {
    card.classList.remove('disabled');
    tag.textContent = generatedLabel;
    tag.classList.remove('not-run');
    card.querySelectorAll('button').forEach(function (b) { b.disabled = false; });
  } else {
    card.classList.add('disabled');
    tag.textContent = 'Not run this session';
    tag.classList.add('not-run');
    card.querySelectorAll('.rc-actions button').forEach(function (b) { b.disabled = true; });
  }
}

function mockDownload(filename) {
  const toast = $('toast');
  if (!toast) return;
  $('toastText').textContent = 'Downloading ' + filename + '…';
  toast.classList.add('show');
  setTimeout(function () { toast.classList.remove('show'); }, 2200);
}
